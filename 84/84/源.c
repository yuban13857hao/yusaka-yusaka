//左移操作符 与 右移操作符
#include<stdio.h>
int main()
{
	//<< 左移操作符（左边丢弃，右边补0）
	//-7的原码10000000000000000000000000000111(首位1为负数，0为正数）
	//反码11111111111111111111111111111000
	//补码11111111111111111111111111111001（反码+1）
	//正数的反码和补码与原码相同
	int a = 7;
	//00000000000000000000000000000111
	int b = a << 1;
	//00000000000000000000000000000110
	printf("%d\n%d\n", a, b);
	int c = -7;//11111111111111111111111111111001
	//11111111111111111111111111110010--->
	//11111111111111111111111111110001-->
	//10000000000000000000000000001110
	int d = c << 1;
	printf("%d\n%d\n", c, d);

	//右移操作符
	//1.算数移动(用的更多)：右边丢弃，左边补原符号
	//2.逻辑移动：右边丢弃，左边补0
	int e = 7;
	int f = e >> 1;
	printf("%d\n%d\n", e, f);
	return 0;
}