#include<stdio.h>
int main()
{
	//&按（二进制）位与
	int  a = 3;
	int b = -5;
	int c = a & b;
	//00000000000000000000000000000011--3的原码
	//10000000000000000000000000000101-（-5）的原码
	//11111111111111111111111111111010-（-5的反码
	//11111111111111111111111111111011-（-5的补码
	//00000000000000000000000000000011--3的补码
	//00000000000000000000000000000011--结果为3
	//有0补0，全1补1
	printf("%d\n", c);

	//|按（二进制）位或
	int  a1 = 3;
	int b1 = -5;
	int c1 = a1 | b1;
	//00000000000000000000000000000011--3的原码
	//10000000000000000000000000000101-（-5）的原码
	//11111111111111111111111111111010-（-5的反码
	//11111111111111111111111111111011-（-5的补码
	//00000000000000000000000000000011--3的补码
	// 
	//11111111111111111111111111111011--补码
	//11111111111111111111111111111010--反码
	//10000000000000000000000000000101-（-5）的源码
	//有1补1，全0补0
	printf("%d\n", c1);

	//^按（二进制）位异或
	int  a2 = 3;
	int b2 = -5;
	int c2 = a2 ^ b2;
	//00000000000000000000000000000011--3的原码
	//10000000000000000000000000000101-（-5）的原码
	//11111111111111111111111111111010-（-5的反码
	//11111111111111111111111111111011-（-5的补码
	//00000000000000000000000000000011--3的补码
	// 
	//11111111111111111111111111111000--补码
	//11111111111111111111111111110111--反码
	//10000000000000000000000000001000-（-8）的源码
	//相同为0，相异为1
	printf("%d\n", c2);
	
	return 0;
}