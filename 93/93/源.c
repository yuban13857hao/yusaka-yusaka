#include<stdio.h>
int main()
{
	//截断与整形提升
	char a = 5;
	//00000000000000000000000000000101
	//00000101
	char b = 126;
	//00000000000000000000000001111110
	//01111110
	char c = a + b;
	//00000101-a
	//01111110-b
	// 整形提升
	//00000000000000000000000000000101
	//00000000000000000000000001111110
	//00000000000000000000000010000011
	//整形截断
	//10000011-c
	//11111111111111111111111110000011-c的补码
	//10000000000000000000000001111100-c的原码（-125）
	printf("%d", c);
	return 0;
}